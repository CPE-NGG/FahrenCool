// Match guidance using the exact condition and therapy mode
export function getConditionGuidance(preset) {
  const key = [
    String(preset.bodyPart || "").trim().toLowerCase(),
    String(preset.guidanceName || preset.name || "").trim(),
    String(preset.condition || "").trim(),
    String(preset.mode || "").trim().toUpperCase()
  ].join("|");

  return BODY_THERAPY_GUIDANCE[key] || {
    why: "Condition-specific educational information is not yet available for this preset.",
    safety: "Seek professional guidance before applying thermal treatment, especially if the cause of symptoms is unknown."
  };
}